type MessageKey = keyof typeof messages.en;
type I18nContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: MessageKey) => string };
const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    const stored = localStorage.getItem("umecke-locale");
    if (stored === "en" || stored === "de" || stored === "tr") { setLocaleState(stored); document.documentElement.lang = stored; }
  }, []);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    localStorage.setItem("umecke-locale", next);
    document.documentElement.lang = next;
  };
  const value = useMemo(() => ({ locale, setLocale, t: (key: MessageKey) => messages[locale][key] ?? messages.en[key] }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside LanguageProvider");
  return value;
}
export function localizedName(value: { name_en?: string | null; name_de?: string | null; name_tr?: string | null }, locale: Locale) {
  return (locale === "de" ? value.name_de : locale === "tr" ? value.name_tr : value.name_en) || value.name_en || value.name_de || value.name_tr || "";
}
